#!/usr/bin/env node
import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import process from 'node:process';

const CHECKED_EXTENSIONS = new Set(['.cjs', '.js', '.jsx', '.mjs', '.py', '.pyi', '.sh', '.ts', '.tsx']);
const SKIPPED_PATH_PARTS = new Set(['__generated__', '__tests__', 'coverage', 'dist', 'docs', 'e2e', 'fixtures', 'node_modules', 'out', 'repro', 'tests']);
const ALLOWED_COMMENT_PATTERN = /(?:@ts-expect-error|@ts-ignore|eslint|shellcheck|istanbul|c8|prettier-ignore|generated|autogenerated|auto-generated|copyright|license|spdx)/i;
const SAFETY_INVARIANT_COMMENT_PATTERN = /safety invariant/i;
const REGEX_PREFIX_KEYWORDS = new Set(['await', 'case', 'delete', 'do', 'else', 'in', 'instanceof', 'new', 'return', 'throw', 'typeof', 'void', 'yield']);
const REGEX_PREFIX_CHARACTERS = new Set(['(', ',', '=', ':', '[', '!', '&', '|', '?', '{', ';', '+', '-', '*', '%', '~', '^', '<', '>']);
const REGEX_LITERAL_TAIL = /^[dgimsuvy]*\s*(?:$|[.,;:)\]}?|&])/;

const MARKDOWN_FENCE_LANGUAGE_EXTENSIONS = new Map([
  ['js', '.js'], ['javascript', '.js'], ['jsx', '.jsx'],
  ['ts', '.ts'], ['typescript', '.ts'], ['tsx', '.tsx'],
  ['mjs', '.mjs'], ['cjs', '.cjs'],
  ['sh', '.sh'], ['bash', '.sh'], ['shell', '.sh'], ['zsh', '.sh'],
  ['py', '.py'], ['python', '.py'],
]);

const MARKDOWN_FILES_GRANDFATHERED_BEFORE_SKILLS_COVERAGE_LANDED = new Set([
  'skills/admin-bypass-sweep/SKILL.md',
  'skills/plan-to-invoker/playbooks/verify-then-build.md',
]);

const PYTHON_FILES_GRANDFATHERED_BEFORE_PYTHON_COVERAGE_LANDED = new Set([
  'scripts/pr_duplicate_close_exec.py',
  'scripts/pr_duplicate_close_git_facts.py',
  'scripts/pr_duplicate_close_model.py',
  'scripts/pr_worker_safe_push.py',
  'scripts/repair_filing_ledger.py',
  'scripts/run_skill_evals.py',
]);

function usage() {
  console.error('Usage: node scripts/check-added-comments.mjs [--base <ref>] [--root <path>] [--file <path>]...');
}

function parseArgs(argv) {
  const parsed = {
    base: process.env.INVOKER_COMMENT_DIFF_BASE || '',
    root: process.cwd(),
    files: [],
  };

  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === '--base') {
      parsed.base = argv[index + 1] || '';
      index += 1;
    } else if (arg.startsWith('--base=')) {
      parsed.base = arg.slice('--base='.length);
    } else if (arg === '--root') {
      parsed.root = argv[index + 1] || '';
      index += 1;
    } else if (arg.startsWith('--root=')) {
      parsed.root = arg.slice('--root='.length);
    } else if (arg === '--file') {
      parsed.files.push(argv[index + 1] || '');
      index += 1;
    } else if (arg.startsWith('--file=')) {
      parsed.files.push(arg.slice('--file='.length));
    } else if (arg === '--help' || arg === '-h') {
      usage();
      process.exit(0);
    } else {
      console.error(`[comments] Unknown argument: ${arg}`);
      usage();
      process.exit(2);
    }
  }

  if (!parsed.root) {
    usage();
    process.exit(2);
  }
  return {
    base: parsed.base,
    root: path.resolve(parsed.root),
    files: parsed.files,
  };
}

/** Diff output scales with the change, so a large PR outgrows Node's 1MB default. */
const GIT_MAX_BUFFER_BYTES = 256 * 1024 * 1024;

function runGit(root, args) {
  return execFileSync('git', args, {
    cwd: root,
    encoding: 'utf8',
    maxBuffer: GIT_MAX_BUFFER_BYTES,
    stdio: ['ignore', 'pipe', 'pipe'],
  });
}

function hasGitRef(root, ref) {
  try {
    runGit(root, ['rev-parse', '--verify', `${ref}^{commit}`]);
    return true;
  } catch {
    return false;
  }
}

function defaultBase(root) {
  const candidates = [];
  if (process.env.GITHUB_BASE_REF) {
    candidates.push(`origin/${process.env.GITHUB_BASE_REF}`);
  }
  candidates.push('origin/master', 'origin/main');

  for (const candidate of candidates) {
    if (hasGitRef(root, candidate)) {
      return candidate;
    }
  }

  if (process.env.CI) {
    console.error('[comments] Could not find a base ref. Set INVOKER_COMMENT_DIFF_BASE.');
    process.exit(2);
  }

  return '';
}

function isCheckedFile(filePath, { ignoreGrandfathered = false } = {}) {
  const normalized = filePath.split(path.sep).join('/');
  const basename = path.basename(normalized);
  const extension = path.extname(basename);

  if (!CHECKED_EXTENSIONS.has(extension)) {
    return false;
  }
  if (basename.endsWith('.d.ts') || basename.includes('.generated.') || basename.includes('.gen.')) {
    return false;
  }
  if (basename.includes('.test.') || basename.includes('.spec.') || basename.includes('.stories.') || basename.startsWith('test-') || basename.startsWith('test_')) {
    return false;
  }
  if (!ignoreGrandfathered && PYTHON_FILES_GRANDFATHERED_BEFORE_PYTHON_COVERAGE_LANDED.has(normalized)) {
    return false;
  }

  const parts = normalized.split('/');
  return !parts.some((part) => SKIPPED_PATH_PARTS.has(part));
}

function isCheckedSkillMarkdownFile(filePath, { ignoreGrandfathered = false } = {}) {
  const normalized = filePath.split(path.sep).join('/');
  if (!normalized.startsWith('skills/') || path.extname(normalized) !== '.md') {
    return false;
  }
  if (!ignoreGrandfathered && MARKDOWN_FILES_GRANDFATHERED_BEFORE_SKILLS_COVERAGE_LANDED.has(normalized)) {
    return false;
  }

  const parts = normalized.split('/');
  return !parts.some((part) => SKIPPED_PATH_PARTS.has(part));
}

function buildMarkdownFenceExtensionMap(content) {
  const map = new Map();
  const lines = content.split('\n');
  let fenceMarker = '';
  let fenceExtension = null;

  for (let index = 0; index < lines.length; index += 1) {
    const line = lines[index];
    const lineNumber = index + 1;
    const fenceOpen = /^\s*(`{3,}|~{3,})\s*([A-Za-z0-9_+-]*)/.exec(line);

    if (fenceMarker) {
      const fenceClose = /^\s*(`{3,}|~{3,})\s*$/.exec(line);
      if (fenceClose && fenceClose[1][0] === fenceMarker[0] && fenceClose[1].length >= fenceMarker.length) {
        fenceMarker = '';
        fenceExtension = null;
        continue;
      }
      if (fenceExtension) {
        map.set(lineNumber, fenceExtension);
      }
      continue;
    }

    if (fenceOpen) {
      fenceMarker = fenceOpen[1];
      fenceExtension = MARKDOWN_FENCE_LANGUAGE_EXTENSIONS.get(fenceOpen[2].toLowerCase()) || null;
    }
  }

  return map;
}

function canStartRegexLiteral(line, index) {
  let previousIndex = index - 1;
  while (previousIndex >= 0 && /\s/.test(line[previousIndex])) {
    previousIndex -= 1;
  }

  if (previousIndex < 0) {
    return true;
  }

  if (REGEX_PREFIX_CHARACTERS.has(line[previousIndex])) {
    return true;
  }

  let tokenStart = previousIndex;
  while (tokenStart >= 0 && /[A-Za-z0-9_$]/.test(line[tokenStart])) {
    tokenStart -= 1;
  }
  return REGEX_PREFIX_KEYWORDS.has(line.slice(tokenStart + 1, previousIndex + 1));
}

function regexLiteralEnd(line, start) {
  let inClass = false;
  for (let index = start + 1; index < line.length; index += 1) {
    const char = line[index];
    if (char === '\\') {
      index += 1;
    } else if (inClass) {
      inClass = char !== ']';
    } else if (char === '[') {
      inClass = true;
    } else if (char === '/') {
      return REGEX_LITERAL_TAIL.test(line.slice(index + 1)) ? index : -1;
    }
  }
  return -1;
}

export function commentIndexForCodeLine(line) {
  let quote = '';
  let escaped = false;

  for (let index = 0; index < line.length; index += 1) {
    const char = line[index];
    const next = line[index + 1] || '';

    if (quote) {
      if (escaped) {
        escaped = false;
      } else if (char === '\\') {
        escaped = true;
      } else if (char === quote) {
        quote = '';
      }
      continue;
    }

    if (char === '"' || char === "'" || char === '`') {
      quote = char;
      continue;
    }
    if (char === '/' && (next === '/' || next === '*')) {
      return index;
    }
    if (char === '/' && canStartRegexLiteral(line, index)) {
      const end = regexLiteralEnd(line, index);
      if (end > index) {
        index = end;
        continue;
      }
    }
    if (char === '*' && next === '/') {
      return index;
    }
  }

  return -1;
}

function scanHashCommentLine(line, initialQuote = '') {
  if (initialQuote === '' && line.startsWith('#!')) {
    return { index: -1, quote: '' };
  }

  let expansionDepth = 0;
  let quote = initialQuote;
  let escaped = false;

  for (let index = 0; index < line.length; index += 1) {
    const char = line[index];
    const next = line[index + 1] || '';

    if (escaped) {
      escaped = false;
      continue;
    }

    if (quote) {
      if (char === '\\' && quote !== "'") {
        escaped = true;
      } else if (char === quote) {
        quote = '';
      }
      continue;
    }

    if (char === '$' && next === '{') {
      expansionDepth += 1;
      index += 1;
      continue;
    }

    if (expansionDepth > 0) {
      if (char === '{') {
        expansionDepth += 1;
      } else if (char === '}') {
        expansionDepth -= 1;
      }
      continue;
    }

    if (char === '"' || char === "'") {
      quote = char;
      continue;
    }
    if (char === '#') {
      return { index, quote };
    }
  }

  return { index: -1, quote };
}

function commentIndexForShellLine(line) {
  return scanHashCommentLine(line, '').index;
}

function commentIndexForExtension(extension, line, fileState) {
  if (extension === '.sh') {
    return commentIndexForShellLine(line);
  }
  if (extension === '.py' || extension === '.pyi') {
    const { index, quote } = scanHashCommentLine(line, fileState.pythonQuote);
    fileState.pythonQuote = quote;
    return index;
  }
  return commentIndexForCodeLine(line);
}

function isAllowedComment(line, index) {
  return ALLOWED_COMMENT_PATTERN.test(line.slice(index));
}

function isSafetyInvariantComment(commentText) {
  return SAFETY_INVARIANT_COMMENT_PATTERN.test(commentText);
}

function pushViolation(violations, source, currentPath, newLine, addedLine) {
  violations.push({
    source,
    path: currentPath,
    line: newLine,
    text: addedLine.trim(),
  });
}

export function collectAddedCommentViolations(diffText, source = 'diff', resolveMarkdownFenceMap = null) {
  const violations = [];
  const lines = diffText.split('\n');
  let currentPath = '';
  let checked = false;
  let isMarkdown = false;
  let newLine = 0;
  let blockComment = null;
  let fileState = { pythonQuote: '', markdownFenceMap: null };

  for (const line of lines) {
    if (line.startsWith('+++ ')) {
      if (blockComment && !blockComment.allowed) {
        violations.push(...blockComment.violations);
      }
      blockComment = null;
      const markerPath = line.slice(4).trim();
      currentPath = markerPath.startsWith('b/') ? markerPath.slice(2) : markerPath;
      isMarkdown = currentPath !== '/dev/null' && isCheckedSkillMarkdownFile(currentPath);
      checked = currentPath !== '/dev/null' && (isCheckedFile(currentPath) || isMarkdown);
      fileState = {
        pythonQuote: '',
        markdownFenceMap: isMarkdown && resolveMarkdownFenceMap ? resolveMarkdownFenceMap(currentPath) : null,
      };
      continue;
    }

    if (line.startsWith('@@ ')) {
      if (blockComment && !blockComment.allowed) {
        violations.push(...blockComment.violations);
      }
      blockComment = null;
      const match = /\+(\d+)(?:,(\d+))?/.exec(line);
      newLine = match ? Number.parseInt(match[1], 10) : 0;
      continue;
    }

    if (!currentPath || newLine < 1) {
      continue;
    }

    if (line.startsWith('+') && !line.startsWith('+++')) {
      const addedLine = line.slice(1);
      if (checked) {
        if (blockComment) {
          blockComment.allowed ||= ALLOWED_COMMENT_PATTERN.test(addedLine);
          if (addedLine.includes('*/')) {
            if (!blockComment.allowed) {
              violations.push(...blockComment.violations);
            }
            blockComment = null;
          }
        } else {
          const extension = isMarkdown
            ? (fileState.markdownFenceMap ? fileState.markdownFenceMap.get(newLine) : null)
            : path.extname(currentPath);
          const index = extension ? commentIndexForExtension(extension, addedLine, fileState) : -1;
          if (index >= 0) {
            const commentText = addedLine.slice(index);
            const startsBlock = commentText.startsWith('/*');
            const closesBlock = startsBlock && commentText.includes('*/', 2);
            const isSingleLineComment = !startsBlock || closesBlock;
            const patternAllowed = isAllowedComment(addedLine, index);
            const allowed = patternAllowed || (isSingleLineComment && isSafetyInvariantComment(commentText));
            if (startsBlock && !closesBlock) {
              blockComment = {
                allowed: patternAllowed,
                violations: patternAllowed ? [] : [{
                  source,
                  path: currentPath,
                  line: newLine,
                  text: addedLine.trim(),
                }],
              };
            } else if (!allowed) {
              pushViolation(violations, source, currentPath, newLine, addedLine);
            }
          }
        }
      }
      newLine += 1;
      continue;
    }

    if (line.startsWith('-') && !line.startsWith('---')) {
      continue;
    }

    if (line.startsWith(' ') || line === '') {
      if (blockComment && !blockComment.allowed) {
        violations.push(...blockComment.violations);
      }
      blockComment = null;
      newLine += 1;
    }
  }

  if (blockComment && !blockComment.allowed) {
    violations.push(...blockComment.violations);
  }

  return violations;
}

function loadGitBlob(root, ref, filePath) {
  try {
    return runGit(root, ['show', `${ref}:${filePath}`]);
  } catch {
    return '';
  }
}

function loadStagedGitBlob(root, filePath) {
  try {
    return runGit(root, ['show', `:${filePath}`]);
  } catch {
    return '';
  }
}

function loadWorkingTreeFile(root, filePath) {
  try {
    return readFileSync(path.join(root, filePath), 'utf8');
  } catch {
    return '';
  }
}

function markdownFenceMapResolver(loadContent) {
  const cache = new Map();
  return (filePath) => {
    if (!cache.has(filePath)) {
      cache.set(filePath, buildMarkdownFenceExtensionMap(loadContent(filePath)));
    }
    return cache.get(filePath);
  };
}

function normalizedRelativeFilePath(root, filePath) {
  const absolutePath = path.resolve(root, filePath);
  const relativePath = path.relative(root, absolutePath);
  if (relativePath.startsWith('..') || path.isAbsolute(relativePath)) {
    console.error(`[comments] --file must be inside --root: ${filePath}`);
    process.exit(2);
  }
  return relativePath.split(path.sep).join('/');
}

function buildFullFileDiffText(relativePath, content) {
  let lines = content === '' ? [] : content.split('\n');
  if (lines.length > 0 && content.endsWith('\n')) {
    lines.pop();
  }

  return [
    `diff --git a/${relativePath} b/${relativePath}`,
    `+++ b/${relativePath}`,
    `@@ -0,0 +1,${lines.length} @@`,
    ...lines.map((line) => `+${line}`),
    '',
  ].join('\n');
}

function fileSources(root, files) {
  return files.map((filePath) => {
    const relativePath = normalizedRelativeFilePath(root, filePath);
    const isMarkdown = isCheckedSkillMarkdownFile(relativePath, { ignoreGrandfathered: true });
    if (!isCheckedFile(relativePath, { ignoreGrandfathered: true }) && !isMarkdown) {
      console.error(`[comments] --file target is not checked by comment policy: ${relativePath}`);
      process.exit(1);
    }

    let content;
    try {
      content = readFileSync(path.join(root, relativePath), 'utf8');
    } catch (error) {
      console.error(`[comments] Failed to read --file target ${relativePath}: ${error.message}`);
      process.exit(1);
    }
    return {
      name: `--file ${relativePath}`,
      text: buildFullFileDiffText(relativePath, content),
      resolveMarkdownFenceMap: markdownFenceMapResolver(() => content),
    };
  });
}

function diffSources(root, base) {
  const sources = [];
  if (base) {
    sources.push({
      name: `${base}...HEAD`,
      text: runGit(root, ['diff', '--unified=0', '--diff-filter=ACMRT', `${base}...HEAD`, '--']),
      resolveMarkdownFenceMap: markdownFenceMapResolver((filePath) => loadGitBlob(root, 'HEAD', filePath)),
    });
  }

  sources.push({
    name: 'staged changes',
    text: runGit(root, ['diff', '--cached', '--unified=0', '--diff-filter=ACMRT', '--']),
    resolveMarkdownFenceMap: markdownFenceMapResolver((filePath) => loadStagedGitBlob(root, filePath)),
  });
  sources.push({
    name: 'working tree changes',
    text: runGit(root, ['diff', '--unified=0', '--diff-filter=ACMRT', '--']),
    resolveMarkdownFenceMap: markdownFenceMapResolver((filePath) => loadWorkingTreeFile(root, filePath)),
  });

  return sources;
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  const sources = args.files.length > 0
    ? fileSources(args.root, args.files)
    : diffSources(args.root, args.base || defaultBase(args.root));
  const violations = sources.flatMap((source) => collectAddedCommentViolations(source.text, source.name, source.resolveMarkdownFenceMap));

  if (violations.length > 0) {
    console.error(`[comments] Found ${violations.length} newly-added comment line(s) in checked source files.`);
    console.error('[comments] Prefer clearer names, smaller functions, or simpler control flow.');
    console.error('[comments] Allowed comments: license, generated markers, tool directives, and rare safety invariants.');
    for (const violation of violations) {
      console.error(`[comments] ${violation.path}:${violation.line} (${violation.source}) ${violation.text}`);
    }
    process.exit(1);
  }

  console.log('[comments] Checked added source lines; no disallowed comments found.');
}

if (fileURLToPath(import.meta.url) === path.resolve(process.argv[1] || '')) {
  main();
}
