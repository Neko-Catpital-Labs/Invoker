#!/usr/bin/env node
import { existsSync, readFileSync, statSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import YAML from 'yaml';

function assert(cond, msg) {
  if (!cond) throw new Error(msg);
}

function fileSha(path) {
  return createHash('sha256').update(readFileSync(path)).digest('hex');
}

const requiredFiles = [
  'MODULE.bazel',
  '.bazelversion',
  '.bazelrc',
  '.bazelignore',
  'BUILD.bazel',
  'buildbuddy.yaml',
  'scripts/bazel/generate-package-build.mjs',
  'scripts/bazel/parity.sh',
  'scripts/bazel/run_pnpm_filter.sh',
  'scripts/bazel/enabled-packages.json',
];
for (const path of requiredFiles) {
  assert(existsSync(path), `missing ${path}`);
}


const bazelignore = readFileSync('.bazelignore', 'utf8');
assert(
  bazelignore.includes('packages/workflow-graph/node_modules'),
  '.bazelignore must list concrete packages/*/node_modules prefixes (globs are not supported)',
);

const bazelrc = readFileSync('.bazelrc', 'utf8');
assert(/build:remote\s+--remote_cache=/.test(bazelrc), '.bazelrc must define build:remote remote_cache');
assert(/build:rbe\s+--remote_executor=/.test(bazelrc), '.bazelrc must define dormant build:rbe remote_executor');
assert(
  !/^build\s+--remote_executor=/m.test(bazelrc),
  'default build must not enable remote_executor (rbe stays behind --config=rbe)',
);

const before = new Map();
for (const path of [
  'BUILD.bazel',
  'scripts/bazel/BUILD.bazel',
  'packages/workflow-graph/BUILD.bazel',
]) {
  if (existsSync(path)) before.set(path, fileSha(path));
}

const gen = spawnSync(process.execPath, ['scripts/bazel/generate-package-build.mjs'], {
  encoding: 'utf8',
});
assert(gen.status === 0, `generator failed: ${gen.stderr || gen.stdout}`);

for (const [path, sha] of before) {
  assert(existsSync(path), `generator removed ${path}`);
  assert(fileSha(path) === sha, `generator is not a no-op for ${path}`);
}

const enabled = JSON.parse(readFileSync('scripts/bazel/enabled-packages.json', 'utf8'));
for (const pkg of enabled.packages ?? []) {
  const buildPath = `packages/${pkg}/BUILD.bazel`;
  assert(existsSync(buildPath), `enabled package missing BUILD.bazel: ${buildPath}`);
  assert(
    readFileSync(buildPath, 'utf8').includes('Generated by scripts/bazel/generate-package-build.mjs'),
    `${buildPath} must be generator-owned`,
  );
}

const mergify = YAML.parse(readFileSync('.mergify.yml', 'utf8'));
const mergeConditions = (mergify.queue_rules ?? [])
  .filter((rule) => rule.name === 'default')
  .flatMap((rule) => rule.merge_conditions ?? [])
  .map(String);
const bazelRequired = mergeConditions.some(
  (c) => c.includes('bazel-cache-pilot') || c.includes('bazel-rbe-pilot') || c.includes('Bazel'),
);
assert(
  !bazelRequired,
  'Mergify default merge_conditions must not require bazel-cache-pilot until the stack-4 cutover',
);

const workflow = YAML.parse(readFileSync('.github/workflows/ci.yml', 'utf8'));
const pilot = workflow.jobs?.['bazel-cache-pilot'];
assert(pilot, 'ci.yml must define bazel-cache-pilot');
assert(pilot['runs-on'] === 'ubuntu-latest', 'bazel-cache-pilot must use ubuntu-latest');
const rbePilot = workflow.jobs?.['bazel-rbe-pilot'];
assert(rbePilot, 'ci.yml must define bazel-rbe-pilot (optional, dormant rbe)');
assert(rbePilot['runs-on'] === 'ubuntu-latest', 'bazel-rbe-pilot must use ubuntu-latest');

console.log('bazel overlay checks passed');
